/**
 * Writes src/docFiles.ts: the docs/ files the site publishes (up to their
 * site-end markers), as strings. The MCP server serves them (get_docs,
 * archer://docs/<page>) and the CLI prints the spec (`archer guide`), so
 * neither reads the repository at runtime. The site reads docs/ itself when
 * it builds. test/docs.test.ts fails while the file is stale.
 *
 * Usage: pnpm --filter @archer/mcp docs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DOC_PAGES, sitePart } from "../src/docPages";

/** A docs file as the site publishes it. */
export const readDocFile = (file: string): string =>
  sitePart(readFileSync(new URL(`../../../docs/${file}`, import.meta.url), "utf8"));

/** Text as a template literal. */
const literal = (text: string) =>
  `\`${text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;

/** The source of src/docFiles.ts: one constant per page with a file, `<PAGE>_DOC`. */
export function docFilesModule(): string {
  const constants = DOC_PAGES.flatMap((p) =>
    p.file
      ? [`/** docs/${p.file}: ${p.title} (${p.path}). */\nexport const ${p.page.toUpperCase()}_DOC = ${literal(readDocFile(p.file))};\n`]
      : [],
  );
  return `// Generated by scripts/docs.ts from the repository's docs/ folder. Don't edit
// by hand: edit the docs file, then run \`pnpm --filter @archer/mcp docs\`.

${constants.join("\n")}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL("../src/docFiles.ts", import.meta.url);
  writeFileSync(out, docFilesModule());
  console.log(`wrote ${fileURLToPath(out)}`);
}
