const require = createRequire(import.meta.url);

/** A regular-weight Phosphor icon as inner markup that paints itself. */
function markup(icon: string): string {
  const svg = readFileSync(require.resolve(`@phosphor-icons/core/regular/${icon}.svg`), "utf8");
  // Every regular icon is one path on a 256 grid; anything else needs a look.
  const m = /^<svg [^>]*viewBox="0 0 256 256"[^>]*><path d="([\d.,\sA-Za-z-]+)"\/><\/svg>\s*$/.exec(svg);
  if (!m) throw new Error(`Unexpected markup in Phosphor's ${icon}.svg`);
  return `<path fill="currentColor" d="${m[1]}"/>`;
}

export const buildGlyphs = (): Record<string, string> =>
  Object.fromEntries(Object.entries(GLYPH_ICONS).map(([key, icon]) => [key, markup(icon)]));

/** The source of src/glyphs.ts. */
export function glyphsModule(): string {
  const glyphs = buildGlyphs();
  const entries = Object.entries(GLYPH_ICONS)
    .map(([key, icon]) => `  // ${icon}\n  ${key}: '${glyphs[key]}',\n`)
    .join("");
  return `// Generated by scripts/glyphs.ts from @phosphor-icons/core. Don't edit by hand:
// change GLYPH_ICONS there, then run \`pnpm --filter @archer/catalog glyphs\`.

/**
 * Component-type glyphs: Phosphor icons (https://phosphoricons.com; MIT,
 * Copyright (c) 2023 Phosphor Icons) at regular weight, drawn in the type's
 * color. Each value is SVG inner markup for GLYPH_VIEWBOX that fills itself
 * with currentColor.
 */
export const GLYPH_VIEWBOX = "0 0 256 256";

export const GLYPHS: Record<string, string> = {
${entries}};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = new URL("../src/glyphs.ts", import.meta.url);
  writeFileSync(out, glyphsModule());
  console.log(`wrote ${fileURLToPath(out)}`);
}
